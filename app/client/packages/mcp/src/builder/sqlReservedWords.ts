// time. Each list is that database's reserved-word list, in lower case. "other" covers SQL Server and Snowflake, so
// their lists are here too. A word on any list is refused on every database, so a query stays valid if its
// datasource changes.
// Sources:
// - PostgreSQL: the "reserved" and "reserved (can be function or type)" words in the SQL Key Words appendix.
// - MySQL 8.0: the words marked (R) in Keywords and Reserved Words.
// - Oracle: the reserved words in V$RESERVED_WORDS (Oracle SQL Reserved Words).
// - SQL Server: the Transact-SQL reserved keywords.
// - Snowflake: the reserved and limited keywords.

